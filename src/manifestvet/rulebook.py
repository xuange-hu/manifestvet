"""Generate the rule reference from the registry.

``docs/rules.md`` is generated, not written: a hand-maintained table of 40 rules
drifts within two commits. ``manifestvet rules --markdown`` prints exactly what the
file must contain, and ``tests/test_docs.py`` asserts the file still matches, so
the document cannot lie about a rule that no longer exists.
"""

from __future__ import annotations

from .rules import REGISTRY, SEVERITY_ORDER

_STAGE_NAMES = {
    1: "element",
    2: "component",
    3: "app",
}


def summary_table() -> str:
    lines = ["| id | severity | stage | rule |", "|---|---|---|---|"]
    for rule in sorted(REGISTRY, key=lambda r: r.id):
        lines.append(f"| `{rule.id}` | {rule.severity} | {_STAGE_NAMES.get(rule.stage, rule.stage)} | {rule.title} |")
    return "\n".join(lines)


def sorted_rules():
    return sorted(REGISTRY, key=lambda r: (SEVERITY_ORDER[r.severity], r.id))


def full_markdown() -> str:
    counts: dict[str, int] = {}
    for rule in REGISTRY:
        counts[rule.severity] = counts.get(rule.severity, 0) + 1
    breakdown = ", ".join(f"{counts[s]} {s}" for s in SEVERITY_ORDER if counts.get(s))

    out = [
        "# Rules",
        "",
        "<!-- Generated by `manifestvet rules --markdown`; edit the rule in",
        "     `src/manifestvet/rules.py` and regenerate. tests/test_docs.py enforces this. -->",
        "",
        f"{len(REGISTRY)} rules ({breakdown}). Every one has a sample manifest that triggers it",
        "(`manifestvet demo` asserts the coverage).",
        "",
        "Stages run in order: **element** rules look at one node, **component** rules at one",
        "component and its intent-filters, **app** rules at the whole manifest.",
        "",
        summary_table(),
        "",
    ]
    for rule in sorted_rules():
        out += [
            f"## {rule.id}",
            "",
            f"**{rule.title}** -- {rule.severity}, stage {rule.stage} ({_STAGE_NAMES.get(rule.stage, '?')})",
            "",
            rule.why,
            "",
            f"**Fix.** {rule.fix}",
            "",
        ]
    return "\n".join(out)
